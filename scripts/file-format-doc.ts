/**
 * Renders docs/file-format.md from the Zod schema (PLAN.md §5: "Zod schemas generate both the
 * runtime validators and the published JSON Schema"). Run `pnpm docs:schema` to regenerate;
 * tests/unit/core/schema.test.ts fails when the committed file is stale.
 */

import { DEFAULT_GLIDE, MOMENT_DEFAULTS } from '../src/core/defaults';
import { MOMENT_TYPES, pieceJsonSchema } from '../src/core/schema';
import {
  TIMBRE_PRESET_FORMAT,
  TIMBRE_PRESET_SUFFIX,
  TIMBRE_PRESET_VERSION,
} from '../src/core/timbre-preset';
import { MAX_VOICES, PIECE_FORMAT, PIECE_VERSION } from '../src/core/types';

export function renderFileFormatDoc(): string {
  const momentDefaults = MOMENT_TYPES.map((type) => {
    const d = MOMENT_DEFAULTS[type];
    const fields = Object.entries(d)
      .map(([k, v]) => `\`${k}\`: \`${JSON.stringify(v)}\``)
      .join(', ');
    return `| \`${type}\` | ${fields === '' ? '(none)' : fields} |`;
  });
  const lines = [
    '# AlgoRhythms file format',
    '',
    '<!-- Generated by `pnpm docs:schema` from src/core/schema.ts. Do not edit by hand. -->',
    '',
    `An AlgoRhythms piece is a JSON file, usually named \`*.algorhythms.json\`. This page describes file format version ${PIECE_VERSION}. The JSON Schema at the end is generated from the Zod schema the app uses to read files, so the two cannot drift apart.`,
    '',
    '## Rules',
    '',
    `- \`format\` must be \`"${PIECE_FORMAT}"\` and \`version\` must be a whole number. Both are required; everything else has a default or is optional.`,
    '- **Defaults.** A field with a `default` in the schema may be left out; it is filled in when the file is read. Leaving out `voices` gives the default pool of 12 voices (`v1`–`v12`).',
    '- **Unknown fields are kept.** Every object accepts extra fields, and the app writes them back when it saves. A file from a newer version survives a round trip through an older one where possible.',
    `- **Versions.** Older files are upgraded on load, one version at a time. A file whose \`version\` is newer than ${PIECE_VERSION} opens with a warning, and the app saves a copy instead of overwriting it. In such a file, moments of unknown types are kept but not played; in a version-${PIECE_VERSION} file they are an error.`,
    `- **Ids.** Voice ids and moment ids must each be unique. Moment ids are normally 6 base62 characters, and they matter: a moment's randomness is seeded from the piece seed and its id. The pool holds at most ${MAX_VOICES} voices.`,
    "- **The start is a moment** (version 2). Every voice starts silent. A `chord` (with notes other than `current`) or a `unison` that comes when nothing is sounding brings its voices in on their notes, with no glide: a new piece opens with a one-note chord at 0. Other moments have no effect from silence. A version 1 file's `start` is upgraded to such a chord at 0 (id `start0`) that keeps each voice on its own pitch (`byVoice`, and a `{ voices }` target when needed).",
    '- **Order matters** in `voices` (the pool index breaks ties) and in `moments` (array order breaks ties between moments at the same time).',
    '- Times are in seconds, pitches are fractional MIDI note numbers (69 = A4), and levels are linear.',
    '',
    '## Defaults for moment fields',
    '',
    `A moment's \`glide\` is partial: missing fields come from \`defaults.glide\`, whose own default is \`${JSON.stringify(DEFAULT_GLIDE)}\`.`,
    '',
    '| Moment type | Defaults filled in |',
    '|---|---|',
    ...momentDefaults,
    '',
    '## Timbre preset files',
    '',
    `The Sound drawer saves one timbre as a preset file, usually named \`*${TIMBRE_PRESET_SUFFIX}\`: an object with \`format\` (\`"${TIMBRE_PRESET_FORMAT}"\`), \`version\` (${TIMBRE_PRESET_VERSION}), \`name\` (1–64 characters) and \`timbre\`, which follows the schema of a \`timbres\` entry below. Defaults fill missing timbre fields and unknown fields are kept, so a preset loads back exactly as it was saved. A newer \`version\` loads with a warning.`,
    '',
    '## JSON Schema',
    '',
    'This is the *input* form: fields with defaults are optional here.',
    '',
    '```json',
    JSON.stringify(pieceJsonSchema(), null, 2),
    '```',
    '',
  ];
  return lines.join('\n');
}
